#!/usr/bin/env node
/**
 * Generates supabase/seed.sql: realistic, deterministic demo data for Tashkent.
 *
 *   node supabase/seed/generate.mjs            write supabase/seed.sql
 *   node supabase/seed/generate.mjs --check    fail if supabase/seed.sql is out of date
 *
 * Deterministic: a fixed PRNG seed and a fixed anchor date (lib/time.mjs), no clock reads, so
 * the output is byte-identical on every machine. The SQL is idempotent (stable ids +
 * `on conflict do nothing`, state moves guarded by the initial state) and runs on the embedded
 * PostgreSQL (auth shim) and on Supabase local. See docs/SEED.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { simulateActivity } from './build/activity.mjs';
import { buildCatalog } from './build/catalog.mjs';
import { buildExtras } from './build/extras.mjs';
import { assignHabits } from './build/habits.mjs';
import { buildConsents, buildPeople } from './build/members.mjs';
import { buildSubscriptions } from './build/subscriptions.mjs';
import { FEATURE_FLAGS } from './data/platform.mjs';
import { STAFF } from './data/people.mjs';
import { seedUuid } from './lib/ids.mjs';
import { createRng } from './lib/prng.mjs';
import { ANCHOR_DATE, HISTORY_DAYS, TIMETABLE_DAYS_AHEAD } from './lib/time.mjs';
import { renderActivity } from './render/activity.mjs';
import { renderCatalog, renderPeople } from './render/identity.mjs';
import { validateModel } from './validate.mjs';

export const PRNG_SEED = 20261012;
const OUTPUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'seed.sql');

export function buildModel() {
  const rng = createRng(PRNG_SEED);
  const catalog = buildCatalog(rng.fork('catalog'));
  const people = buildPeople(rng);
  assignHabits(rng, people, catalog.venues);

  const venueBySlug = new Map(catalog.venues.map((v) => [v.slug, v]));
  const personByKey = new Map(people.map((p) => [p.key, p]));
  const staffLinks = STAFF.flatMap((s) =>
    s.venues.map(([slug, role]) => ({
      id: seedUuid('venue-staff', s.key, slug),
      venueId: venueBySlug.get(slug).id,
      userId: personByKey.get(s.key).id,
      role,
      createdAt: Math.max(personByKey.get(s.key).signupAt, venueBySlug.get(slug).createdAt),
    })),
  );
  const staffByVenue = new Map();
  for (const link of staffLinks)
    staffByVenue.set(link.venueId, [...(staffByVenue.get(link.venueId) ?? []), link.userId]);

  const money = buildSubscriptions(rng, people, catalog.plans);
  const activity = simulateActivity(rng, {
    catalog,
    people,
    subscriptions: money.subscriptions,
    staffByVenue,
  });
  const extras = buildExtras(rng, { ...catalog, people, ...money, ...activity });
  return {
    ...catalog,
    flags: FEATURE_FLAGS,
    people,
    staffLinks,
    consents: buildConsents(people),
    ...money,
    ...activity,
    ...extras,
  };
}

export function renderSeed(model) {
  const header = `-- Demo seed data: ${model.venues.length} venues in Tashkent, ${model.people.length} accounts, ${model.visits.length} visits.
-- GENERATED by supabase/seed/generate.mjs (PRNG seed ${PRNG_SEED}). Do not edit by hand:
-- change the generator and run "node supabase/seed/generate.mjs". See docs/SEED.md.
-- Anchor ${ANCHOR_DATE} 00:00 Asia/Tashkent: history covers the ${HISTORY_DAYS} days before it, the class
-- timetable runs ${TIMETABLE_DAYS_AHEAD} days after it. Idempotent: safe to re-run on a seeded database.
`;
  return [header, renderCatalog(model), renderPeople(model), renderActivity(model)].join('\n');
}

function main() {
  const model = buildModel();
  validateModel(model);
  const sql = renderSeed(model);
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUTPUT, 'utf8').replaceAll('\r\n', '\n');
    if (current !== sql) {
      console.error('supabase/seed.sql is out of date: run "node supabase/seed/generate.mjs"');
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(OUTPUT, sql);
  const count = (list, pred = () => true) => list.filter(pred).length;
  console.log(
    `seed.sql written (${(Buffer.byteLength(sql) / 1024).toFixed(0)} KiB): ` +
      `${count(model.venues, (v) => v.status === 'active')}/${model.venues.length} active venues, ` +
      `${count(model.sessions)} class sessions, ${count(model.people, (p) => p.kind === 'member')} members, ` +
      `${count(model.subscriptions, (s) => s.status === 'active')} active subscriptions, ` +
      `${count(model.bookings)} bookings, ${count(model.visits)} visits, ${count(model.reviews)} reviews`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
