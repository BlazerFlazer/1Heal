/** Typographic characters shared by the formatters. */

/** NO-BREAK SPACE: thousands separator and the gap between a number and its unit. */
export const NBSP = ' ';

/** MINUS SIGN (not a hyphen) for negative amounts. */
export const MINUS_SIGN = '−';

/** EN DASH for ranges: "09:00–10:30", "8–12 окт". */
export const EN_DASH = '–';
